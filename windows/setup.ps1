# AI お絵描き — Windows PC の設定（サーバー版）
#  公開したURLを Chrome の全画面（キオスク）で開くショートカットを作ります。
#  1) デスクトップにショートカット「AIお絵描き」
#  2) （任意）スタートアップに登録 → PC起動時に自動で全画面起動
#  3) 印刷は Chrome の自動印刷（確認ダイアログなしで既定のプリンターへ）
#
#  使い方: windows\setup.bat をダブルクリック
#          URL を指定するとき: setup.bat -Url "https://ai-art.example.com"
param(
    [string]$Url = '',
    [switch]$Yes
)

$ErrorActionPreference = 'Stop'
$AppName = 'AIお絵描き'
$Home2   = Join-Path $env:LOCALAPPDATA 'AIDrawingKiosk'   # 設定と Chrome 専用プロファイルの置き場所

function Info($m) { Write-Host "  $m" }
function Ok($m)   { Write-Host "  [OK] $m" -ForegroundColor Green }
function Warn($m) { Write-Host "  [注意] $m" -ForegroundColor Yellow }
function Ask($q, $defaultYes) {
    if ($Yes) { return $defaultYes }
    $suffix = if ($defaultYes) { '[Y/n]' } else { '[y/N]' }
    $a = Read-Host "  $q $suffix"
    if ([string]::IsNullOrWhiteSpace($a)) { return $defaultYes }
    return $a -match '^[yY]'
}

Write-Host ''
Write-Host '============================================================'
Write-Host "  $AppName  Windows PC の設定（サーバー版）"
Write-Host '============================================================'

# --- URL ---
if (-not $Url) {
    $urlFile = Join-Path $PSScriptRoot 'kiosk_url.txt'
    if (Test-Path $urlFile) {
        $Url = (Get-Content $urlFile -Encoding UTF8 | Where-Object { $_ -match '^\s*https?://' } | Select-Object -First 1)
        if ($Url) { $Url = $Url.Trim(); Info "kiosk_url.txt の URL を使います: $Url" }
    }
}
while (-not $Url) {
    $Url = (Read-Host '  公開した URL を入力してください（例: https://ai-art.example.com）').Trim()
    if ($Url -and $Url -notmatch '^https?://') { Warn 'http:// か https:// から入力してください'; $Url = '' }
}
$Url = $Url.TrimEnd('/')
if ($Url -notmatch '^https://' -and $Url -notmatch '^http://(localhost|127\.0\.0\.1)') {
    Warn 'https:// でない URL はマイクが使えません。公開先は https にしてください。'
}

# --- Chrome ---
$chrome = @(
    "$env:ProgramFiles\Google\Chrome\Application\chrome.exe",
    "${env:ProgramFiles(x86)}\Google\Chrome\Application\chrome.exe",
    "$env:LOCALAPPDATA\Google\Chrome\Application\chrome.exe"
) | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
if (-not $chrome) {
    Write-Host '  [エラー] Google Chrome が見つかりません。https://www.google.com/chrome/ からインストールしてから、もう一度実行してください。' -ForegroundColor Red
    exit 1
}
Ok "Chrome: $chrome"

# --- 起動スクリプト（ネットにつながるまで待ってから Chrome を全画面で開く） ---
New-Item -ItemType Directory -Force -Path $Home2 | Out-Null
$profileDir = Join-Path $Home2 'chrome-profile'
$chromeArgs = @(
    "--kiosk `"$Url/`"",
    "--kiosk-printing",                        # 印刷の確認ダイアログを出さず既定のプリンターへ
    "--user-data-dir=`"$profileDir`"",         # 普段の Chrome とは別の専用プロファイル（ログイン状態を保持）
    "--no-first-run", "--no-default-browser-check",
    "--disable-session-crashed-bubble", "--hide-crash-restore-bubble",
    "--disable-pinch", "--overscroll-history-navigation=0",
    "--disable-features=Translate,TranslateUI",
    "--use-fake-ui-for-media-stream",          # マイク許可を毎回聞かない
    "--autoplay-policy=no-user-gesture-required"
) -join ' '

$vbsPath = Join-Path $Home2 'start.vbs'
$q = '"'
$vbs = @"
' AI Drawing kiosk launcher (generated by windows\setup.ps1)
' usage: wscript start.vbs [delay_seconds]
Option Explicit
Dim sh, url, chrome, args, delay, i, http, ok
Set sh = CreateObject("WScript.Shell")
url = "$Url"
chrome = "$chrome"
args = "$($chromeArgs.Replace($q, $q + $q))"
delay = 0
If WScript.Arguments.Count > 0 Then delay = CInt(WScript.Arguments(0))
If delay > 0 Then WScript.Sleep delay * 1000
ok = False
For i = 1 To 45
  On Error Resume Next
  Set http = CreateObject("MSXML2.ServerXMLHTTP.6.0")
  http.setTimeouts 3000, 3000, 5000, 5000
  http.open "GET", url & "/healthz", False
  http.send
  If Err.Number = 0 Then
    If http.status = 200 Then ok = True
  End If
  Err.Clear
  On Error GoTo 0
  If ok Then Exit For
  WScript.Sleep 2000
Next
sh.Run Chr(34) & chrome & Chr(34) & " " & args, 1, False
"@
# 日本語のユーザー名でも動くよう UTF-16 で保存（WSH が読める形式）
Set-Content -Path $vbsPath -Value $vbs -Encoding Unicode
Set-Content -Path (Join-Path $Home2 'url.txt') -Value $Url -Encoding UTF8
Ok '起動スクリプトを作成しました'

# --- ショートカット ---
$wscript = Join-Path $env:WINDIR 'System32\wscript.exe'
$shell = New-Object -ComObject WScript.Shell
function New-KioskShortcut([string]$lnkPath, [string]$extraArgs) {
    $s = $shell.CreateShortcut($lnkPath)
    $s.TargetPath = $wscript
    $s.Arguments = "`"$vbsPath`" $extraArgs".Trim()
    $s.WorkingDirectory = $Home2
    $s.IconLocation = "$chrome,0"
    $s.Description = $AppName
    $s.Save()
}
$desktopLnk = Join-Path ([Environment]::GetFolderPath('Desktop')) "$AppName.lnk"
New-KioskShortcut $desktopLnk ''
Ok "デスクトップにショートカットを作成: $AppName"

$startupLnk = Join-Path ([Environment]::GetFolderPath('Startup')) "$AppName.lnk"
if (Ask 'PC起動（サインイン）時に自動で全画面起動しますか？' $true) {
    New-KioskShortcut $startupLnk '10'     # 起動直後は10秒待ってから
    Ok 'スタートアップに登録しました（設定 > アプリ > スタートアップ でON/OFFできます）'
} elseif (Test-Path $startupLnk) {
    Remove-Item $startupLnk -Force
    Info 'スタートアップ登録を解除しました'
}

# --- スリープ（任意） ---
if (Ask '展示用に、スリープと画面オフを無効にしますか？（電源設定を変更します）' $false) {
    powercfg /change standby-timeout-ac 0
    powercfg /change monitor-timeout-ac 0
    powercfg /change standby-timeout-dc 0
    powercfg /change monitor-timeout-dc 0
    Ok 'スリープ・画面オフを無効にしました'
}

Write-Host ''
Write-Host '============================================================'
Write-Host '  設定完了'
Write-Host "  ・起動: デスクトップの「$AppName」"
Write-Host '  ・初回だけ: 全画面でログイン画面が出るので ID とパスワードを入力'
Write-Host '  ・閉じる: Alt+F4'
Write-Host '  ・管理画面: タイトル2秒長押し → 暗証番号'
Write-Host '  ・印刷: Windows の「既定のプリンター」に、確認なしで印刷されます'
Write-Host '          （設定 > Bluetooth とデバイス > プリンターとスキャナー で既定と用紙A5を設定）'
Write-Host '============================================================'

if (Ask 'プリンターの設定画面を開きますか？' $false) { Start-Process 'ms-settings:printers' }
if (Ask '今すぐ起動してログインしますか？' $true) { Start-Process $wscript -ArgumentList "`"$vbsPath`"" }
